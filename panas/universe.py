def get_panas_for_digit(digit: int, pana_type: str = None) -> list:
    """
    Returns the list of valid Panas for a given digit.
    Optionally filter by pana_type ('SP', 'DP', 'TP').
    """
    if digit not in MASTER_PANNAS:
        return []
        
    if pana_type:
        return MASTER_PANNAS[digit].get(pana_type, [])
        
    # Return all (SP + DP + TP)
    return (
        MASTER_PANNAS[digit]['SP'] + 
        MASTER_PANNAS[digit]['DP'] + 
        MASTER_PANNAS[digit]['TP']
    )
